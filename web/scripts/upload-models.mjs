// Uploads the home page's 3D models to Cloudinary (as raw files: served byte for byte, never re-processed) and writes
// their URLs to src/lib/models.ts, which the site reads. Re-run after rebuilding or adding a model:
//   node scripts/upload-models.mjs            (from web/; reads CLOUDINARY_* from web/.env)
// Each URL carries Cloudinary's version number, which changes on every upload, so browsers never keep a stale model.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const WEB = path.resolve(import.meta.dirname, "..");
process.loadEnvFile(path.join(WEB, ".env"));
const { CLOUDINARY_CLOUD_NAME: cloud, CLOUDINARY_API_KEY: key, CLOUDINARY_API_SECRET: secret } = process.env;
if (!cloud || !key || !secret) throw new Error("Set CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET in web/.env");

const FOLDER = "fmd/models";
// every model the home page loads, by its path under web/public
const FILES = [
  "/mascot-sitting-raw.glb", // hero, desktop
  "/mascot-sitting-raw-mobile.glb", // hero, phones and low-memory devices
  "/models/assistant.glb", // FMD AI's mascot beside the search bar
  ...["guide", "guide-left", "laptop", "reading", "scholar", "vault", "butler", "pin", "heart", "tooth"].map((n) => `/models/rig/${n}.glb`),
];

async function upload(file) {
  // raw public ids keep their extension; the local folders are mirrored under FOLDER (models/rig/x → fmd/models/rig/x)
  const public_id = `${FOLDER}/${file.replace(/^\/(models\/)?/, "")}`;
  const params = { invalidate: "true", overwrite: "true", public_id, timestamp: String(Math.floor(Date.now() / 1000)) };
  const toSign = Object.keys(params).sort().map((k) => `${k}=${params[k]}`).join("&");
  const form = new FormData();
  for (const [k, v] of Object.entries(params)) form.append(k, v);
  form.append("api_key", key);
  form.append("signature", createHash("sha1").update(toSign + secret).digest("hex"));
  form.append("file", new Blob([readFileSync(path.join(WEB, "public", file))]), path.basename(file));
  const res = await fetch(`https://api.cloudinary.com/v1_1/${cloud}/raw/upload`, { method: "POST", body: form });
  const data = await res.json();
  if (!res.ok) throw new Error(`${file}: ${data.error?.message ?? res.status}`);
  console.log(`uploaded ${file} (${(data.bytes / 1024 / 1024).toFixed(2)} MB) → ${data.secure_url}`);
  return [file, data.secure_url];
}

const urls = [];
for (const f of FILES) urls.push(await upload(f)); // one at a time: a few MB each, keeps errors readable

writeFileSync(
  path.join(WEB, "src/lib/models.ts"),
  `// Generated by scripts/upload-models.mjs: every 3D model on the home page, served from Cloudinary. Don't edit by hand;
// re-run the script after rebuilding a model. A path missing here falls back to the local copy in web/public.
export const MODEL_CDN: Record<string, string> = ${JSON.stringify(Object.fromEntries(urls), null, 2)};

/** The CDN URL of a model, by its path under web/public (e.g. "/models/rig/guide.glb"). */
export const model = (localPath: string) => MODEL_CDN[localPath] ?? localPath;
`,
);
console.log(`wrote src/lib/models.ts (${urls.length} models)`);
